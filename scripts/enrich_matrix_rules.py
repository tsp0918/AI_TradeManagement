def main():
    print(f"DB: {DB_PATH}")
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    # まず 削除 ステータスをスキップ（title/req_text='削除' のものは更新しない）
    skip_ids = set()
    cur.execute("SELECT id, title FROM matrix_rules WHERE title='削除'")
    for row in cur.fetchall():
        skip_ids.add(row[0])

    updated = 0
    skipped_deleted = 0
    not_found = []

    for rule_id, new_text in ENRICHMENTS.items():
        if rule_id in skip_ids:
            skipped_deleted += 1
            continue

        cur.execute("SELECT id, requirement_text FROM matrix_rules WHERE id=?", (rule_id,))
        row = cur.fetchone()
        if row is None:
            not_found.append(rule_id)
            continue

        cur.execute(
            "UPDATE matrix_rules SET requirement_text=? WHERE id=?",
            (new_text.strip(), rule_id),
        )
        updated += 1

    conn.commit()
    conn.close()

    print(f"Updated : {updated}")
    print(f"Skipped (削除): {skipped_deleted}")
    if not_found:
        print(f"Not found IDs: {not_found}")
    print("Done.")


if __name__ == "__main__":
    main()
